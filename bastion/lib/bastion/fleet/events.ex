defmodule Bastion.Fleet.Events do
  @moduledoc """
  Доменные события контекста Fleet. Публикуются в тему `:fleet` и
  `{:device, id}` (только события одного устройства):

  - `DeviceRequested` — новая заявка (или повторная);
  - `DeviceApproved` — заявка одобрена, в событии сертификат для устройства;
  - `DeviceRevoked` — устройство отозвано: его соединение нужно закрыть;
  - `DeviceChanged` — любое видимое изменение (имя, папка, статус, удаление);
  - `FoldersChanged` — папки созданы, переименованы или удалены.
  """
end
